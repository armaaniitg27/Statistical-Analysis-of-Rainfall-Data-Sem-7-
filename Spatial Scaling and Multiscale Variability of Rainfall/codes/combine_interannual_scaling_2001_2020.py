df_early = pd.DataFrame(early_results)
FILE_LATE = os.path.join(RESULTS_DIR, 'interannual_scaling_zeta2_2018_2020.csv')
if not os.path.exists(FILE_LATE):
    raise FileNotFoundError('\nCould not find:\n' + FILE_LATE + '\n\nMake sure the 2018-2020 script was run successfully first.')
df_late = pd.read_csv(FILE_LATE)
df = pd.concat([df_early, df_late], ignore_index=True)
df = df.sort_values('year').reset_index(drop=True)
df['zeta2_difference'] = df['lon_zeta2'] - df['lat_zeta2']
df['zeta2_ratio'] = df['lon_zeta2'] / df['lat_zeta2']
expected_years = list(range(2001, 2021))
actual_years = df['year'].astype(int).tolist()
if actual_years != expected_years:
    raise ValueError('\nYear coverage is incorrect.')
if df['year'].duplicated().any():
    raise ValueError('\nDuplicate years detected.')
combined_file = os.path.join(RESULTS_DIR, 'interannual_scaling_zeta2_2001_2020_COMPLETE.csv')
df.to_csv(combined_file, index=False)
summary = pd.DataFrame({'Longitude_zeta2': [df['lon_zeta2'].mean(), df['lon_zeta2'].std(), df['lon_zeta2'].min(), df['lon_zeta2'].max(), df['lon_zeta2'].max() - df['lon_zeta2'].min()], 'Latitude_zeta2': [df['lat_zeta2'].mean(), df['lat_zeta2'].std(), df['lat_zeta2'].min(), df['lat_zeta2'].max(), df['lat_zeta2'].max() - df['lat_zeta2'].min()], 'Difference': [df['zeta2_difference'].mean(), df['zeta2_difference'].std(), df['zeta2_difference'].min(), df['zeta2_difference'].max(), df['zeta2_difference'].max() - df['zeta2_difference'].min()], 'Ratio': [df['zeta2_ratio'].mean(), df['zeta2_ratio'].std(), df['zeta2_ratio'].min(), df['zeta2_ratio'].max(), df['zeta2_ratio'].max() - df['zeta2_ratio'].min()]}, index=['mean', 'std', 'minimum', 'maximum', 'range'])
summary.loc['coefficient_of_variation', 'Longitude_zeta2'] = df['lon_zeta2'].std() / df['lon_zeta2'].mean()
summary.loc['coefficient_of_variation', 'Latitude_zeta2'] = df['lat_zeta2'].std() / df['lat_zeta2'].mean()
summary.loc['coefficient_of_variation', 'Difference'] = df['zeta2_difference'].std() / df['zeta2_difference'].mean()
summary.loc['coefficient_of_variation', 'Ratio'] = df['zeta2_ratio'].std() / df['zeta2_ratio'].mean()
summary_file = os.path.join(RESULTS_DIR, 'interannual_scaling_zeta2_summary_2001_2020.csv')
summary.to_csv(summary_file)
lon_greater = (df['lon_zeta2'] > df['lat_zeta2']).sum()
lat_greater = (df['lat_zeta2'] > df['lon_zeta2']).sum()
equal = (df['lon_zeta2'] == df['lat_zeta2']).sum()
